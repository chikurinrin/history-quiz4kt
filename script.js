function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  document.getElementById('screen-' + id).classList.add('active');
}

function goHome() {
  showScreen('home');
  renderEraList();
  renderStats();
  renderMissList();
  updateHeader();
}

// =====================================================
// ERA UTILITIES
// =====================================================
function getEraMap() {
  const m = {};
  allQuestions.forEach(q => { m[q.era] = (m[q.era] || 0) + 1; });
  return m;
}

function getEraAccuracy(era) {
  const acc = appState.accuracy[era];
  if (!acc || acc.total === 0) return null;
  return Math.round(acc.correct / acc.total * 100);
}

function accuracyColor(pct) {
  if (pct >= 80) return '#3d6b4f';
  if (pct >= 50) return '#b8880a';
  return '#b83232';
}

// =====================================================
// ERA LIST
// =====================================================
function renderEraList() {
  const eraMap = getEraMap();
  const list = document.getElementById('era-list');
  list.innerHTML = '';

  ERA_ORDER.forEach(era => {
    if (!eraMap[era]) return;
    const count = eraMap[era];
    const isSelected = selectedEras.has(era);
    const pct = getEraAccuracy(era);

    const item = document.createElement('div');
    item.className = 'era-item' + (isSelected ? ' selected' : '');
    item.onclick = () => toggleEra(era);

    const accuracyHtml = pct !== null
      ? `<span class="era-accuracy" style="color:${accuracyColor(pct)}">${pct}%</span>`
      : '';

    item.innerHTML = `
      <div class="era-cb">${isSelected ? '✓' : ''}</div>
      <span class="era-name">${era}</span>
      ${accuracyHtml}
      <span class="era-count">${count}問</span>
    `;
    list.appendChild(item);
  });

  updateStartBtn();
}

function toggleEra(era) {
  if (selectedEras.has(era)) selectedEras.delete(era);
  else selectedEras.add(era);
  renderEraList();
}

function selectAllEras(select) {
  const eraMap = getEraMap();
  if (select) ERA_ORDER.forEach(e => { if (eraMap[e]) selectedEras.add(e); });
  else selectedEras.clear();
  renderEraList();
}

function updateStartBtn() {
  document.getElementById('start-selected-btn').disabled = selectedEras.size === 0;
}

