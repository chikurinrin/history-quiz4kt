function answer(knew) {
  const q = quiz.questions[quiz.index];

  if (knew) {
    quiz.correct++;
    appState.sessionCorrect++;
    appState.missIds = appState.missIds.filter(id => id !== q.id);
  } else {
    quiz.wrong++;
    appState.sessionWrong++;
    if (!appState.missIds.includes(q.id)) appState.missIds.push(q.id);
  }

  if (!appState.accuracy[q.era]) appState.accuracy[q.era] = { correct: 0, total: 0 };
  appState.accuracy[q.era].total++;
  if (knew) appState.accuracy[q.era].correct++;

  if (!quiz.eraResults[q.era]) quiz.eraResults[q.era] = { correct: 0, total: 0 };
  quiz.eraResults[q.era].total++;
  if (knew) quiz.eraResults[q.era].correct++;

  saveState();
  updateHeader();
  showReveal(q, knew);
}

function showReveal(q, knew) {
  const headerClass = knew ? 'correct-header' : 'wrong-header';
  const mark = knew ? '⭕' : '❌';
  const status = knew ? '正解！' : '不正解';
  const reviseBtn = !knew
    ? `<button class="revise-btn" id="revise-btn" onclick="markRevised()">✓ 理解できた（復習リストから外す）</button>`
    : '';

  document.getElementById('quiz-area').innerHTML = `
    <div class="q-card">
      <div class="q-category">${q.cat}</div>
      <div class="q-text">${q.q}</div>
    </div>
    <div class="reveal-panel">
      <div class="reveal-header ${headerClass}">
        <span class="reveal-mark">${mark}</span>
        <span class="reveal-status">${status}</span>
      </div>
      <div class="reveal-body">
        <div class="answer-label">正 解</div>
        <div class="answer-text">${q.a}</div>
        ${q.exp ? `<div class="explanation">${q.exp}</div>` : ''}
      </div>
    </div>
    ${reviseBtn}
    <button class="next-btn" onclick="nextQuestion()">次の問題へ →</button>
  `;
}

function markRevised() {
  const q = quiz.questions[quiz.index];
  appState.missIds = appState.missIds.filter(id => id !== q.id);
  saveState();
  updateHeader();
  const btn = document.getElementById('revise-btn');
  if (btn) {
    btn.textContent = '✓ 復習リストから外しました';
    btn.disabled = true;
    btn.style.opacity = '0.5';
  }
}

function nextQuestion() {
  quiz.index++;
  showQuestion();
}

