const ERA_ORDER = [
  '縄文弥生古墳','飛鳥','奈良','平安','鎌倉',
  '室町','安土桃山','江戸前期','江戸後期',
  '幕末','明治前期','明治後期'
];

const STORAGE_KEY = 'history-quiz-kota-v1';

let appState = {
  missIds: [],
  accuracy: {},
  sessionCorrect: 0,
  sessionWrong: 0,
};

let quiz = {
  questions: [],
  index: 0,
  correct: 0,
  wrong: 0,
  mode: 'all',
  eraResults: {},
};

let selectedEras = new Set();

// =====================================================
// STORAGE
// =====================================================
function loadState() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const data = JSON.parse(saved);
      appState.missIds = data.missIds || [];
      appState.accuracy = data.accuracy || {};
      appState.sessionCorrect = data.sessionCorrect || 0;
      appState.sessionWrong = data.sessionWrong || 0;
    }
  } catch (e) {}
}

function saveState() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(appState));
  } catch (e) {}
}

