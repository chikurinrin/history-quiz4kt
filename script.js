function showResult() {
  showScreen('result');

  const total = quiz.questions.length;
  const correct = quiz.correct;
  const pct = total > 0 ? Math.round(correct / total * 100) : 0;

  document.getElementById('res-correct').textContent = correct;
  document.getElementById('res-denom').textContent = `/ ${total}問 正解`;

  let msg;
  if (pct >= 90) msg = '完璧に近い出来です！この調子で頑張ろう！';
  else if (pct >= 80) msg = '優秀！あと少しで満点です！';
  else if (pct >= 70) msg = 'よくできました！引き続き頑張りましょう。';
  else if (pct >= 50) msg = 'もう一息！間違えた問題を復習しましょう。';
  else msg = '基礎からしっかり復習しましょう。焦らずに！';

  document.getElementById('res-msg').textContent = `正答率 ${pct}%　${msg}`;

  const missBtn = document.getElementById('res-miss-btn');
  if (quiz.wrong > 0) {
    missBtn.style.display = 'block';
    missBtn.textContent = `間違えた ${quiz.wrong} 問を復習する`;
  } else {
    missBtn.style.display = 'none';
  }

  document.getElementById('progress-fill').style.width = '100%';
  document.getElementById('progress-label').textContent = `${total}/${total}`;

  const eraKeys = ERA_ORDER.filter(e => quiz.eraResults[e]);
  const breakdown = document.getElementById('result-era-breakdown');
  const rows = document.getElementById('result-era-rows');

  if (eraKeys.length > 1) {
    breakdown.style.display = 'block';
    rows.innerHTML = '';
    eraKeys.forEach(era => {
      const r = quiz.eraResults[era];
      const p = Math.round(r.correct / r.total * 100);
      const color = accuracyColor(p);
      const row = document.createElement('div');
      row.className = 'result-era-row';
      row.innerHTML = `
        <span class="result-era-name">${era}</span>
        <div class="result-era-bar-wrap">
          <div class="result-era-bar" style="width:${p}%;background:${color}"></div>
        </div>
        <span class="result-era-pct" style="color:${color}">${p}%</span>
        <span class="result-era-detail">${r.correct}/${r.total}</span>
      `;
      rows.appendChild(row);
    });
  } else {
    breakdown.style.display = 'none';
  }
}

