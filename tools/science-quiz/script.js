function showResult() {
  showScreen('result');
  const total = sessionResults.length;
  const correct = sessionResults.filter(r => r.correct).length;
  const pct = total > 0 ? Math.round(correct / total * 100) : 0;

  document.getElementById('res-correct').textContent = correct;
  document.getElementById('res-denom').textContent = `/ ${total}問 正解（${pct}%）`;

  const msgs = [
    [90, '素晴らしい！完璧に近い正答率です。'],
    [70, 'よくできました！苦手な単元を重点的に復習しましょう。'],
    [50, 'もう少しです。間違えた問題を繰り返し練習しましょう。'],
    [0,  '復習が必要です。基礎から確認していきましょう。'],
  ];
  document.getElementById('res-msg').textContent = (msgs.find(([t]) => pct >= t) || msgs[msgs.length - 1])[1];

  const missCnt = sessionResults.filter(r => !r.correct).length;
  const missBtn = document.getElementById('res-miss-btn');
  if (missCnt > 0) { missBtn.style.display = ''; missBtn.textContent = `間違えた${missCnt}問を復習する`; }
  else missBtn.style.display = 'none';

  // Subject breakdown
  const breakdown = {};
  sessionResults.forEach(r => {
    if (!breakdown[r.subject]) breakdown[r.subject] = { correct: 0, total: 0 };
    breakdown[r.subject].total++;
    if (r.correct) breakdown[r.subject].correct++;
  });

  const rows = Object.entries(breakdown).map(([s, v]) => {
    const p = v.total > 0 ? Math.round(v.correct / v.total * 100) : 0;
    return `<div class="result-row">
      <div class="result-row-name">${getSubjectLabel(s)}</div>
      <div class="result-bar-wrap"><div class="result-bar" style="width:${p}%;background:${getSubjectColor(s)}"></div></div>
      <div class="result-row-pct" style="color:${getSubjectColor(s)}">${p}%</div>
      <div class="result-row-detail">${v.correct}/${v.total}</div>
    </div>`;
  }).join('');

  const bd = document.getElementById('result-breakdown');
  if (rows) { bd.style.display = ''; bd.querySelector('#result-rows').innerHTML = rows; }
  else bd.style.display = 'none';
}

