function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function getSubjectLabel(s) {
  return { physics:'物理', chemistry:'化学', biology:'生物', earthscience:'地学' }[s] || s;
}

function getSubjectColor(s) {
  return { physics:'var(--physics)', chemistry:'var(--chemistry)', biology:'var(--biology)', earthscience:'var(--earth)' }[s] || 'var(--primary)';
}

function getLevelLabel(l) {
  return { basic:'基礎', standard:'標準', advanced:'発展' }[l] || l;
}

