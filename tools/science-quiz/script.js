const STORAGE_KEY = 'science-quiz-v1';

let state = {
  missedIds: [],
  subjectStats: {},
  unitStats: {},
};

function loadState() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) state = { ...state, ...JSON.parse(saved) };
  } catch {}
}

function saveState() {
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch {}
}

