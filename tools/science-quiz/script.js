function renderQuestion() {
  if (sessionIndex >= sessionQuestions.length) {
    showResult();
    return;
  }

  const q = sessionQuestions[sessionIndex];
  const pct = Math.round(sessionIndex / sessionQuestions.length * 100);
  document.getElementById('progress-fill').style.width = pct + '%';
  document.getElementById('progress-label').textContent = `${sessionIndex + 1} / ${sessionQuestions.length}`;

  const area = document.getElementById('quiz-area');
  area.innerHTML = `
    <div class="q-card">
      <div class="q-meta">
        <span class="q-subject-tag" style="background:${getSubjectColor(q.subject)}">${getSubjectLabel(q.subject)}</span>
        <span class="q-unit">${q.unit}</span>
        <span class="q-level level-${q.level}">${getLevelLabel(q.level)}</span>
      </div>
      <div class="q-text">${q.q}</div>
    </div>
    <div id="answer-area"></div>
  `;

  if (q.type === 'mc') renderMcOptions(q);
  else renderQaButtons(q);
}

function renderMcOptions(q) {
  const area = document.getElementById('answer-area');
  area.innerHTML = `<div class="mc-options">` +
    q.options.map((opt, i) =>
      `<button class="mc-btn" onclick="selectMc(${i})">${String.fromCharCode(65 + i)}. ${opt}</button>`
    ).join('') +
    `</div>`;
}

function selectMc(chosen) {
  const q = sessionQuestions[sessionIndex];
  const correct = chosen === q.correct;
  recordAnswer(q, correct);

  const btns = document.querySelectorAll('.mc-btn');
  btns.forEach((btn, i) => {
    btn.disabled = true;
    if (i === q.correct) btn.classList.add('correct');
    else if (i === chosen && !correct) btn.classList.add('wrong');
  });

  renderRevealPanel(q, correct);
}

function renderQaButtons(q) {
  const area = document.getElementById('answer-area');
  area.innerHTML = `<button class="reveal-btn" onclick="revealAnswer()">答えを確認する</button>`;
}

function revealAnswer() {
  const q = sessionQuestions[sessionIndex];
  const area = document.getElementById('answer-area');
  area.innerHTML = `
    <div class="answer-box">
      <div class="answer-label">答え</div>
      <div class="answer-text">${q.a}</div>
      ${q.exp ? `<div class="explanation">${q.exp}</div>` : ''}
    </div>
    <div class="self-check">
      <button class="self-btn know" onclick="selfCheck(true)">✓ わかった</button>
      <button class="self-btn dontknow" onclick="selfCheck(false)">✗ わからなかった</button>
    </div>
  `;
}

function selfCheck(correct) {
  const q = sessionQuestions[sessionIndex];
  recordAnswer(q, correct);
  renderRevealPanel(q, correct);
  document.querySelector('.self-check').remove();
}

function renderRevealPanel(q, correct) {
  const area = document.getElementById('quiz-area');
  const existing = area.querySelector('.reveal-panel');
  if (existing) existing.remove();

  const panel = document.createElement('div');
  panel.className = 'reveal-panel';
  panel.innerHTML = `
    <div class="reveal-header ${correct ? 'correct-header' : 'wrong-header'}">
      <span class="reveal-mark">${correct ? '◯' : '✗'}</span>
      <span class="reveal-status">${correct ? '正解！' : '不正解'}</span>
    </div>
    ${q.type === 'mc' ? `
    <div class="reveal-body">
      <div class="answer-label">解説</div>
      <div class="explanation">${q.exp}</div>
    </div>` : ''}
    <div class="reveal-actions">
      ${!correct ? `<button class="revise-btn" onclick="addMiss(${q.id})">復習リストに追加</button>` : ''}
      <button class="next-btn" onclick="nextQuestion()">次の問題 →</button>
    </div>
  `;
  area.appendChild(panel);
}

function addMiss(id) {
  if (!state.missedIds.includes(id)) {
    state.missedIds.push(id);
    saveState();
  }
}

function recordAnswer(q, correct) {
  sessionResults.push({ id: q.id, subject: q.subject, unit: q.unit, correct });

  if (!state.subjectStats[q.subject]) state.subjectStats[q.subject] = { correct: 0, total: 0 };
  state.subjectStats[q.subject].total++;
  if (correct) state.subjectStats[q.subject].correct++;

  const uk = q.subject + '|' + q.unit;
  if (!state.unitStats[uk]) state.unitStats[uk] = { correct: 0, total: 0 };
  state.unitStats[uk].total++;
  if (correct) state.unitStats[uk].correct++;

  if (correct && state.missedIds.includes(q.id)) {
    state.missedIds = state.missedIds.filter(id => id !== q.id);
  }
  if (!correct && !state.missedIds.includes(q.id)) {
    state.missedIds.push(q.id);
  }

  saveState();
}

function nextQuestion() {
  sessionIndex++;
  renderQuestion();
}

