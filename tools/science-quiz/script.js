function filterBySubject(qs) {
  if (currentSubject === 'all') return qs;
  return qs.filter(q => q.subject === currentSubject);
}

function startMode(mode) {
  let qs = [];
  currentMode = mode;

  if (mode === 'all') {
    qs = filterBySubject([...allQuestions]);
  } else if (mode === 'shuffle') {
    qs = shuffle(filterBySubject([...allQuestions])).slice(0, 30);
  } else if (mode === 'miss') {
    qs = allQuestions.filter(q => state.missedIds.includes(q.id));
    qs = filterBySubject(qs);
    if (qs.length === 0) { alert('間違えた問題がありません！'); return; }
  } else if (mode === 'basic' || mode === 'standard' || mode === 'advanced') {
    qs = filterBySubject(allQuestions.filter(q => q.level === mode));
  } else if (mode === 'selected') {
    qs = allQuestions.filter(q => _selectedUnits.has(q.subject + '|' + q.unit));
    if (qs.length === 0) { alert('単元を選択してください。'); return; }
  }

  if (qs.length === 0) { alert('該当する問題がありません。'); return; }

  sessionQuestions = shuffle(qs);
  sessionIndex = 0;
  sessionResults = [];
  showScreen('quiz');
  renderQuestion();
}

let _lastMode = '';
function retryMode() { startMode(currentMode); }

