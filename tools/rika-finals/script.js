/* ===========================================================
   出題開始
   =========================================================== */
function startMode(mode){
  let list;
  if (mode==='all') list = [...QUESTIONS];
  else if (mode==='shuffle') list = shuffle([...QUESTIONS]).slice(0,20);
  else if (mode==='miss'){
    list = QUESTIONS.filter(q=>wrongSet.has(q.id));
    if (list.length===0){ alert('復習する問題がありません。まずは出題に挑戦しましょう！'); return; }
  }
  else if (mode==='selected'){
    list = QUESTIONS.filter(q=>selectedUnits.has(q.u));
    if (list.length===0){ alert('単元を選んでください。'); return; }
  }
  else list = [...QUESTIONS];

  session = { list, idx:0, mode, correct:0, wrong:0, skip:0 };
  renderQuestion();
  show('screen-quiz');
}
function retryMode(){ if(session) startMode(session.mode); }

function shuffle(a){ for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];} return a; }

/* ===========================================================
   問題描画
   =========================================================== */
function renderQuestion(){
  const s = session;
  const q = s.list[s.idx];
  const cat = CATS[UNITS[q.u].cat];

  // 進捗
  const prog = ((s.idx)/s.list.length)*100;
  document.getElementById('progress-fill').style.width = prog+'%';
  document.getElementById('progress-label').textContent = `${s.idx+1}/${s.list.length}`;

  const area = document.getElementById('quiz-area');
  const isReview = wrongSet.has(q.id);

  let body = '';
  if (q.type==='mc'){
    // 選択問題
    body = `<div class="mc-options" id="mc-options">` +
      q.choices.map((c,i)=>`<button class="mc-btn" onclick="answerMC(${i})">${c}</button>`).join('') +
      `</div>`;
  } else {
    // 記述（自己採点）
    body = `<button class="reveal-btn" onclick="reveal()">答えを見る</button>`;
  }

  area.innerHTML =
    `<div class="q-card">
       <div class="q-meta">
         <span class="q-subject-tag" style="background:${cat.color}">${cat.short}</span>
         <span class="q-unit">${UNITS[q.u].name}</span>
         ${isReview?'<span class="q-review">要復習</span>':''}
       </div>
       <div class="q-text">${q.q}</div>
     </div>
     <div id="answer-area">${body}</div>`;
}

/* 記述：答えを表示 */
function reveal(){
  const q = session.list[session.idx];
  document.getElementById('answer-area').innerHTML =
    `<div class="answer-box">
       <div class="answer-label">こたえ</div>
       <div class="answer-text">${q.a}</div>
       ${q.e?`<div class="explanation">💡 ${q.e}</div>`:''}
     </div>` + selfCheckHTML();
}

/* 選択問題：回答 */
function answerMC(sel){
  const q = session.list[session.idx];
  const btns = document.querySelectorAll('#mc-options .mc-btn');
  btns.forEach((b,i)=>{
    b.disabled = true;
    if (i===q.ans) b.classList.add('correct');
    else if (i===sel) b.classList.add('wrong');
  });
  const ok = sel===q.ans;
  const area = document.getElementById('answer-area');
  area.insertAdjacentHTML('beforeend',
    `<div class="answer-box" style="margin-top:10px">
       <div class="reveal-header ${ok?'correct-header':'wrong-header'}" style="margin:-16px -18px 12px;border-radius:8px 8px 0 0">
         <span class="reveal-mark">${ok?'⭕':'❌'}</span>
         <span class="reveal-status">${ok?'正解！':'不正解'}</span>
       </div>
       <div class="answer-label">こたえ</div>
       <div class="answer-text">${q.a}</div>
       ${q.e?`<div class="explanation">💡 ${q.e}</div>`:''}
     </div>` + selfCheckHTML(ok));
}

/* 自己採点ボタン（3択）
   preset: 選択問題で自動判定済みのとき true/false を渡す */
function selfCheckHTML(preset){
  const recommend = preset===undefined ? '' :
    (preset ? '<div class="sc-hint">正解でした。「わかった」で記録しましょう。</div>'
            : '<div class="sc-hint">不正解でした。「わからなかった」で復習リストへ。</div>');
  return `
    <div class="self-check-wrap">
      ${recommend}
      <div class="self-check">
        <button class="self-btn know" onclick="judge('correct')">⭕ わかった<span>正解として記録</span></button>
        <button class="self-btn dontknow" onclick="judge('wrong')">❌ わからなかった<span>復習リストへ</span></button>
      </div>
      <button class="self-btn skip" onclick="judge('skip')">➖ カウントしない<span>記録せず次へ進む</span></button>
    </div>`;
}

/* 判定 → 記録 → 次へ */
function judge(result){
  const q = session.list[session.idx];
  if (result==='correct'){
    session.correct++; stats.correct++;
    wrongSet.delete(q.id);            // 正解したら復習リストから外す
  } else if (result==='wrong'){
    session.wrong++; stats.wrong++;
    wrongSet.add(q.id);              // 間違えたら復習リストへ
  } else {
    session.skip++;                  // カウントしない：統計も復習も変更しない
  }
  saveWrong(); saveStats();
  next();
}

function next(){
  session.idx++;
  if (session.idx>=session.list.length) finish();
  else renderQuestion();
}

/* ===========================================================
   結果画面
   =========================================================== */
function finish(){
  const s = session;
  const graded = s.correct + s.wrong;
  const pct = graded? Math.round(s.correct/graded*100):0;

  document.getElementById('res-correct').textContent = s.correct;
  document.getElementById('res-denom').textContent =
    `／ ${graded}問中 正解（カウントしない ${s.skip}問）`;

  let msg, icon;
  if (graded===0){ icon='➖'; msg='すべて「カウントしない」でした。気軽に確認できましたか？'; }
  else if (pct>=90){ icon='🏆'; msg=`正答率${pct}%！この調子なら期末で90点以上を狙えます。間違えた問題だけ復習して完璧に！`; }
  else if (pct>=70){ icon='💪'; msg=`正答率${pct}%。あと少し！「間違えた問題を復習」で弱点をつぶしましょう。`; }
  else { icon='📖'; msg=`正答率${pct}%。まずは間違えた問題を繰り返し復習。基礎用語から固めれば必ず伸びます。`; }

  document.getElementById('result-icon').textContent = icon;
  document.getElementById('res-msg').textContent = msg;
  document.getElementById('res-miss-btn').style.display = wrongSet.size? 'block':'none';
  document.getElementById('res-miss-btn').textContent = `間違えた問題を復習する（${wrongSet.size}問）`;

  show('screen-result');
}

