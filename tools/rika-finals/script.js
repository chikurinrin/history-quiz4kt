function resetAll(){
  if (!confirm('正解数・間違い記録・復習リストをすべて消去します。よろしいですか？')) return;
  wrongSet = new Set(); stats = { correct:0, wrong:0 };
  saveWrong(); saveStats();
  renderHome();
}

