// ═══════════════════════════════════════════════════════
//  STATE
// ═══════════════════════════════════════════════════════
const state = {
  screen: 'home',
  unitFilter: null,
  questions: [],
  index: 0,
  score: 0,
  wrong: [],
  cardState: 'front',   // 'front' | 'flipped' | 'quiz'
  answered: false,
  progress: {},
};

// ─── Storage helpers ───
const STORAGE_KEY = 'meiji-exam-v1';
function loadProgress() {
  try { return JSON.parse(localStorage.getItem(STORAGE_KEY) || '{}'); }
  catch { return {}; }
}
function saveProgress() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state.progress));
}

// ─── Utils ───
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// ─── Progress calculations ───
function unitProgress(uid) {
  const qs = QUESTIONS.filter(q => q.unit === uid);
  const done = qs.filter(q => state.progress[q.id] === true).length;
  return { total: qs.length, done };
}

function overallProgress() {
  const total = QUESTIONS.length;
  const done  = QUESTIONS.filter(q => state.progress[q.id] === true).length;
  return { total, done };
}

// ─── Header stats ───
function updateHeaderStats() {
  const ok  = Object.values(state.progress).filter(v => v === true).length;
  const ng  = Object.values(state.progress).filter(v => v === false).length;
  const all = QUESTIONS.length;
  document.getElementById('hstat-ok').textContent  = ok;
  document.getElementById('hstat-ng').textContent  = ng;
  document.getElementById('hstat-all').textContent = all;
}

// ═══════════════════════════════════════════════════════
//  SCREEN MANAGEMENT
// ═══════════════════════════════════════════════════════
function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  document.getElementById(id).classList.add('active');
  window.scrollTo(0, 0);
}

// ═══════════════════════════════════════════════════════
//  HOME SCREEN
// ═══════════════════════════════════════════════════════
function renderHome() {
  const { total, done } = overallProgress();
  const pct = total ? Math.round(done / total * 100) : 0;
  document.getElementById('overall-pct').textContent   = pct + '%';
  document.getElementById('overall-done').textContent  = done;
  document.getElementById('overall-total').textContent = total;
  document.getElementById('overall-bar').style.width   = pct + '%';

  const grid = document.getElementById('unit-grid');
  grid.innerHTML = '';
  UNITS.forEach(u => {
    const prog = unitProgress(u.id);
    const upct = prog.total ? Math.round(prog.done / prog.total * 100) : 0;
    const check = upct >= 100 ? '✓' : '';
    const card = document.createElement('button');
    card.className = 'unit-card';
    card.style.background = `linear-gradient(135deg, ${u.color} 0%, ${u.color}cc 100%)`;
    card.innerHTML = `
      <div class="unit-num">UNIT ${u.id}　${u.pages}</div>
      <div class="unit-name">${u.name}</div>
      <div class="unit-prog"><div class="unit-prog-fill" style="width:${upct}%"></div></div>
      <div class="unit-sub">${prog.done} / ${prog.total} 問正解</div>
      ${check ? `<div class="unit-check">${check}</div>` : ''}
    `;
    card.addEventListener('click', () => startSession('flash', u.id));
    grid.appendChild(card);
  });

  showScreen('screen-home');
}

// ═══════════════════════════════════════════════════════
//  SESSION START
// ═══════════════════════════════════════════════════════
function startSession(mode, unitId) {
  state.unitFilter = unitId;
  state.index      = 0;
  state.score      = 0;
  state.wrong      = [];
  state.cardState  = 'front';
  state.answered   = false;

  let pool = unitId ? QUESTIONS.filter(q => q.unit === unitId) : [...QUESTIONS];

  if (mode === 'weak') {
    pool = pool.filter(q => state.progress[q.id] === false);
    if (!pool.length) {
      alert('苦手問題はまだありません！まずは学習に挑戦してみよう。');
      return;
    }
  }
  state.questions = shuffle(pool);
  renderCard();
  showScreen('screen-quiz');
}

