// ─── Storage helpers ───
const STORAGE_KEY = 'meiji-exam-v1';
function loadProgress() {
  try { return JSON.parse(localStorage.getItem(STORAGE_KEY) || '{}'); }
  catch { return {}; }
}
function saveProgress() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state.progress));
}

// ─── Utils ───
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// ─── Progress calculations ───
function unitProgress(uid) {
  const qs = QUESTIONS.filter(q => q.unit === uid);
  const done = qs.filter(q => state.progress[q.id] === true).length;
  return { total: qs.length, done };
}

function overallProgress() {
  const total = QUESTIONS.length;
  const done  = QUESTIONS.filter(q => state.progress[q.id] === true).length;
  return { total, done };
}

// ─── Header stats ───
function updateHeaderStats() {
  const ok  = Object.values(state.progress).filter(v => v === true).length;
  const ng  = Object.values(state.progress).filter(v => v === false).length;
  const all = QUESTIONS.length;
  document.getElementById('hstat-ok').textContent  = ok;
  document.getElementById('hstat-ng').textContent  = ng;
  document.getElementById('hstat-all').textContent = all;
}

// ═══════════════════════════════════════════════════════
//  SCREEN MANAGEMENT
